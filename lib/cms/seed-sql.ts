/**
 * SQL for supabase/seed.sql, generated from the real website content (see seed-data.ts).
 *
 * The SQL is idempotent: every insert uses ON CONFLICT DO NOTHING, so running it again never
 * duplicates records and never overwrites content edited in the dashboard.
 */
import { seedItems, seedPages, seedSections, seedSettings } from "@/lib/cms/seed-data";
import { collectionKeys, collectionRegistry } from "@/lib/cms/registry";
import { buildSite } from "@/lib/cms/site";

const TAG = "$cms_json$";

function json(v: unknown): string {
  const text = JSON.stringify(v);
  if (text.includes(TAG)) throw new Error(`Content contains the reserved marker ${TAG}`);
  return `${TAG}${text}${TAG}::jsonb`;
}

function str(v: string | null): string {
  return v === null ? "null" : `'${v.replace(/'/g, "''")}'`;
}

/** Built from the bundled defaults (not pulled CMS content), so the file is reproducible. */
export function buildSeedSql(): string {
  const site = buildSite();
  const lines: string[] = [
    "-- =============================================================================",
    "--  Hybrid Hearts CMS — initial content (generated by `npm run cms:seed-sql`)",
    "--  Source: content/*.ts via lib/cms/seed-data.ts. Do not edit by hand.",
    "--  Idempotent: existing records are never duplicated or overwritten.",
    "-- =============================================================================",
    "",
  ];

  for (const p of seedPages(site)) {
    lines.push(
      `insert into public.cms_pages (id, route, label, sort, is_template, draft, published, published_at) values (${str(p.id)}, ${str(p.route)}, ${str(p.label)}, ${p.sort}, ${p.is_template}, ${json(p.draft)}, ${json(p.published)}, now()) on conflict (id) do nothing;`,
    );
  }
  lines.push("");

  for (const s of seedSections(site)) {
    lines.push(
      `insert into public.cms_sections (page_id, key, label, section_type, ref_key, required, position, visible, draft, published, published_position, published_visible, published_at) values (${str(s.page_id)}, ${str(s.key)}, ${str(s.label)}, ${str(s.section_type)}, ${str(s.ref_key)}, ${s.required}, ${s.position}, ${s.visible}, ${json(s.draft)}, ${json(s.published)}, ${s.published_position}, ${s.published_visible}, now()) on conflict (page_id, key) do nothing;`,
    );
  }
  lines.push("");

  const settings = seedSettings(site);
  lines.push(
    `insert into public.cms_settings (id, draft, published, published_at) values ('site', ${json(settings.draft)}, ${json(settings.published)}, now()) on conflict (id) do nothing;`,
    "",
  );

  for (const key of collectionKeys) {
    const table = collectionRegistry[key].table;
    for (const item of seedItems(key, site)) {
      const extraCols = [
        ...(item.consent_confirmed !== undefined ? ["consent_confirmed"] : []),
        ...(item.category !== undefined ? ["category"] : []),
      ];
      const extraVals = [
        ...(item.consent_confirmed !== undefined ? [String(item.consent_confirmed)] : []),
        ...(item.category !== undefined ? [str(item.category)] : []),
      ];
      const cols = ["import_key", "slug", "position", "visible", "draft", "published", "published_at", ...extraCols].join(", ");
      const vals = [str(item.import_key), str(item.slug), item.position, item.visible, json(item.draft), json(item.published), "now()", ...extraVals].join(", ");
      lines.push(`insert into public.${table} (${cols}) values (${vals}) on conflict do nothing;`);
    }
    lines.push("");
  }

  return `${lines.join("\n")}\n`;
}
